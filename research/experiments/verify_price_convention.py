"""Decide which return convention the ``raw_hfq_pct/`` cache actually carries.

Why this exists
---------------
A 2026 forward window has to be **spliced onto** the cached series, and the
splice rule is only correct if the cached returns mean what we think they mean.
Getting it wrong does not raise: it silently shifts every derived feature on the
2026 dates (a dividend-sized step, ~2%/yr), so the whole forward read-out
becomes uninterpretable.  Hence this check runs *before* any forward result is
produced.

The directory is called ``raw_hfq_pct`` and ``data_api.py:282-334`` compounds a
``pct_change`` column and rescales OHLC, which reads like 后复权.  But the
rescaling is a no-op for returns (it multiplies OHLC by one per-row factor and
then *recomputes* ``pct_change`` from the rescaled close), so the directory name
tells us nothing about the **return** convention.  That depends entirely on
where the input ``pct_change`` column came from:

* tushare ``daily.pct_chg`` -- adjusted for corporate actions (its ``pre_close``
  is the ex-rights previous close), i.e. total-return-like;
* a local ``close.pct_change()`` -- raw, dividend-excluded.

Four candidate conventions are tested against the cache's own returns:

===============  =====================================================
``raw_close``    ``tushare.close.pct_change()``      -- dividend-excluded
``tushare_pct``  ``tushare.pct_chg``                 -- tushare's own field
``adj_factor``   ``(close * adj_factor).pct_change()``  -- 后复权
``pre_close``    ``close / pre_close - 1``           -- tushare's adjusted prev
===============  =====================================================

Judgement (pre-registered in ``docs/research/04_validation_and_diagnostics/forward_paper_tracking_2026.md``
§2): a convention is **confirmed** only if the maximum absolute return
difference vs the cache stays below ``1e-4`` on every sampled symbol.  A
near-miss that only differs on ex-dividend days is exactly the failure this is
built to catch, so per-day mismatch counts are reported alongside the max.

Example::

    python -m research.experiments.verify_price_convention --limit 4   # smoke
    python -m research.experiments.verify_price_convention             # full
"""

import argparse
import json
import re
import sys
import time
from pathlib import Path
from typing import Dict, List, Optional, Sequence, Tuple

import numpy as np
import pandas as pd

from research.experiments.fetch_tushare_daily_basic import call_api, read_token

CACHE_DIR = Path("data/raw/tushare/price_history/raw_hfq_pct")
OUTPUT_DIR = Path("data/raw/tushare/forward_2026/convention_check")
POOL_FILES = {"hs300": Path("data/HS300.txt"), "zz1000": Path("data/ZZ_1000.txt")}

DAILY_FIELDS = "ts_code,trade_date,open,high,low,close,pre_close,change,pct_chg,vol,amount"
ADJ_FIELDS = "ts_code,trade_date,adj_factor"

CONVENTIONS = ("raw_close", "tushare_pct", "adj_factor", "pre_close")

# The pre-registered bar: below this the convention counts as confirmed.
TOLERANCE = 1e-4


def load_pool_codes(path: Path) -> List[str]:
    """Bare 6-digit codes from a pool list file, order preserved."""

    codes = []
    for line in path.read_text(encoding="utf-8").splitlines():
        digits = line.strip().split(".")[0]
        if re.fullmatch(r"\d{6}", digits):
            codes.append(digits)
    return codes


def cached_symbols() -> Dict[str, Path]:
    """``bare code -> newest cached file`` over the price-history cache."""

    best: Dict[str, Path] = {}
    for path in CACHE_DIR.glob("*.csv"):
        match = re.match(r"(\d{6})\.[A-Z]{2}_\d+_(\d+)\.csv$", path.name)
        if not match:
            continue
        code, end = match.group(1), match.group(2)
        if code not in best or end > best[code].name.split("_")[-1].split(".")[0]:
            best[code] = path
    return best


def pick_symbols(pools: Dict[str, Path], per_pool: int) -> List[Tuple[str, str]]:
    """``(pool, ts_code)`` sample: ``per_pool`` names from each pool that exist locally."""

    available = cached_symbols()
    picked: List[Tuple[str, str]] = []
    for pool, path in pools.items():
        taken = 0
        for code in load_pool_codes(path):
            if taken >= per_pool:
                break
            hit = available.get(code)
            if hit is None:
                continue
            ts_code = hit.name.split("_")[0]
            picked.append((pool, ts_code))
            taken += 1
    return picked


def load_cached_returns(ts_code: str) -> pd.DataFrame:
    """Cached close + its own ``pct_change``, restricted to rows with data.

    ``pct_change`` is recomputed from the cached close rather than trusted
    verbatim: it is stored in percent and was itself regenerated by the cache
    writer, so recomputing keeps this comparison independent of formatting.
    """

    path = cached_symbols().get(ts_code.split(".")[0])
    if path is None:
        raise FileNotFoundError("no cached file for {}".format(ts_code))
    frame = pd.read_csv(path, usecols=["date", "close"], low_memory=False)
    frame["date"] = pd.to_datetime(frame["date"], errors="coerce")
    frame["close"] = pd.to_numeric(frame["close"], errors="coerce")
    frame = frame.dropna(subset=["date", "close"]).sort_values("date")
    frame["cached_return"] = frame["close"].pct_change()
    return frame.loc[:, ["date", "close", "cached_return"]]


def fetch_symbol_frames(
    ts_code: str, token: str, library: Path, start: str, end: str,
    retries: int, sleep: float, force: bool,
) -> Tuple[pd.DataFrame, pd.DataFrame]:
    """``(daily, adj_factor)`` for one symbol, cached per symbol and per table."""

    library.mkdir(parents=True, exist_ok=True)
    frames = []
    for name, api_name, fields in (("daily", "daily", DAILY_FIELDS),
                                   ("adj_factor", "adj_factor", ADJ_FIELDS)):
        path = library / "{}_{}.csv".format(name, ts_code)
        if path.exists() and not force:
            frames.append(pd.read_csv(path, dtype={"ts_code": str, "trade_date": str},
                                      low_memory=False))
            continue
        frame = call_api(api_name, token,
                         {"ts_code": ts_code, "start_date": start, "end_date": end},
                         fields=fields, retries=retries)
        frame.to_csv(path, index=False, encoding="utf-8-sig")
        frames.append(frame)
        if sleep:
            time.sleep(sleep)
    return frames[0], frames[1]


def build_candidates(daily: pd.DataFrame, adj: pd.DataFrame) -> Optional[pd.DataFrame]:
    """All four candidate return series on one date index, or ``None`` if too thin."""

    if daily is None or daily.empty:
        return None
    frame = daily.copy()
    frame["date"] = pd.to_datetime(frame["trade_date"], format="%Y%m%d", errors="coerce")
    for column in ("close", "pre_close", "pct_chg"):
        frame[column] = pd.to_numeric(frame[column], errors="coerce")
    frame = frame.dropna(subset=["date", "close"]).sort_values("date")

    if adj is not None and not adj.empty:
        factor = adj.copy()
        factor["date"] = pd.to_datetime(factor["trade_date"], format="%Y%m%d", errors="coerce")
        factor["adj_factor"] = pd.to_numeric(factor["adj_factor"], errors="coerce")
        frame = frame.merge(factor.loc[:, ["date", "adj_factor"]], on="date", how="left")
    else:
        frame["adj_factor"] = np.nan

    pre_close = frame["pre_close"].where(frame["pre_close"] > 0)
    frame["raw_close"] = frame["close"].pct_change()
    frame["tushare_pct"] = frame["pct_chg"] / 100.0
    adjusted = frame["close"] * frame["adj_factor"]
    frame["adj_factor"] = adjusted.pct_change()
    frame["pre_close"] = frame["close"] / pre_close - 1.0
    return frame


def compare(ts_code: str, pool: str, merged: pd.DataFrame) -> List[dict]:
    """Per-convention agreement between the cache and each candidate."""

    rows = []
    merged = merged.dropna(subset=["cached_return"])
    for name in CONVENTIONS:
        candidate = merged[name]
        both = merged.loc[candidate.notna(), ["date", "cached_return", name]]
        if both.empty:
            rows.append({"pool": pool, "ts_code": ts_code, "convention": name,
                         "days": 0, "max_abs_diff": np.nan, "mismatch_days": 0,
                         "first_mismatch": None})
            continue
        diff = (both["cached_return"] - both[name]).abs()
        bad = diff > TOLERANCE
        rows.append({
            "pool": pool, "ts_code": ts_code, "convention": name,
            "days": int(len(diff)),
            "max_abs_diff": float(diff.max()),
            "mismatch_days": int(bad.sum()),
            "first_mismatch": (str(both.loc[diff.idxmax(), "date"].date())
                               if bad.any() else None),
        })
    return rows


def parse_args(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", default=str(OUTPUT_DIR))
    parser.add_argument("--start-date", default="20250101")
    parser.add_argument("--end-date", default="20251231")
    parser.add_argument("--per-pool", type=int, default=14)
    parser.add_argument("--limit", type=int, default=None, help="only the first N symbols (smoke)")
    parser.add_argument("--env-file", default=".env")
    parser.add_argument("--sleep", type=float, default=0.35)
    parser.add_argument("--retries", type=int, default=6)
    parser.add_argument("--force", action="store_true")
    return parser.parse_args(argv)


def main(argv=None) -> int:
    args = parse_args(argv)
    output_dir = Path(args.output_dir)
    library = output_dir / "tushare"

    token = read_token(Path(args.env_file))
    sample = pick_symbols(POOL_FILES, args.per_pool)
    if args.limit:
        sample = sample[: args.limit]
    print("sampling {} symbols ({} per pool)".format(
        len(sample), args.per_pool), flush=True)

    rows, failures = [], []
    for pool, ts_code in sample:
        try:
            daily, adj = fetch_symbol_frames(ts_code, token, library, args.start_date,
                                             args.end_date, args.retries, args.sleep, args.force)
        except Exception as exc:
            failures.append({"pool": pool, "ts_code": ts_code, "error": str(exc)[:200]})
            continue
        merged = build_candidates(daily, adj)
        if merged is None:
            failures.append({"pool": pool, "ts_code": ts_code, "error": "empty daily"})
            continue
        cached = load_cached_returns(ts_code)
        merged = merged.merge(cached.loc[:, ["date", "cached_return"]], on="date", how="inner")
        rows += compare(ts_code, pool, merged)
        print("  {:<10} {:>5} overlapping days".format(ts_code, len(merged)), flush=True)

    if not rows:
        print("no comparable rows; failures: {}".format(failures), file=sys.stderr)
        return 1

    table = pd.DataFrame(rows)
    summary = table.groupby("convention").agg(
        symbols=("ts_code", "nunique"),
        days=("days", "sum"),
        mismatch_days=("mismatch_days", "sum"),
        worst_symbol_max_abs_diff=("max_abs_diff", "max"),
    ).reindex(CONVENTIONS)

    output_dir.mkdir(parents=True, exist_ok=True)
    table.to_csv(output_dir / "per_symbol.csv", index=False, encoding="utf-8-sig")
    summary.to_csv(output_dir / "summary.csv", encoding="utf-8-sig")

    print("\n=== convention agreement vs cached raw_hfq_pct returns ===")
    print(summary.to_string())
    print("\ntolerance = {:g}".format(TOLERANCE))

    confirmed = [name for name in CONVENTIONS
                 if summary.loc[name, "worst_symbol_max_abs_diff"] < TOLERANCE]
    print("confirmed: {}".format(confirmed or "NONE"))
    (output_dir / "verdict.json").write_text(json.dumps({
        "start_date": args.start_date, "end_date": args.end_date,
        "symbols": int(table["ts_code"].nunique()), "tolerance": TOLERANCE,
        "confirmed": confirmed,
        "summary": summary.reset_index().to_dict(orient="records"),
        "failures": failures,
    }, ensure_ascii=False, indent=2), encoding="utf-8")
    return 0 if confirmed else 2


if __name__ == "__main__":
    raise SystemExit(main())
